-- This file is the single source of the module's texts: the C++ module and
-- the upgrade window (sent to the client by data/lua/ItemUpgrade_Serveur.lua)
-- read them from here, and neither carries a text of its own.
--
-- English in `module_string`; every other language in `module_string_locale`.
-- Each player gets the row of their client's language, English when it has
-- none. Numbers:
--   1-99       messages of the C++ module (src/item_upgrade.h, ItemUpgradeTexts);
--              the window shows 1-9 too, when the module refuses an upgrade;
--   101-199    the upgrade window (ID in ItemUpgrade_Client.lua);
--   1000 + n   the name of statistic n (ItemModType of the core);
--   1100 + n   the name of equipment slot n (EquipmentSlots of the core).
-- A number is never reused once retired.
--
-- Adding a language takes one INSERT per number into `module_string_locale`,
-- with the locale code of that client (deDE, esES, ruRU...): no rebuild, only a
-- restart. `{}` stands for a value and must be kept, as many times as in English.

